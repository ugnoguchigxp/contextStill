//! Wire contract. Source support, identity and final adoption remain host-side policy gates.
use serde_json::{json, Value};
fn object(properties: Value) -> Value {
    let required = properties
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect::<Vec<_>>();
    json!({"type":"object","additionalProperties":false,"required":required,"properties":properties})
}
fn text(max: usize) -> Value {
    json!({"type":"string","maxLength":max})
}
fn array(items: Value, max: usize) -> Value {
    json!({"type":"array","items":items,"maxItems":max})
}
pub(crate) fn format(covering: bool, negative: bool, finalizing: bool) -> Value {
    let evidence = array(
        object(
            json!({"snapshotHash":text(128),"text":text(1024),"role":text(128),"fromByte":{"type":["integer","null"],"minimum":0}}),
        ),
        32,
    );
    let candidate = object(
        json!({"candidate":object(json!({"type":{"type":"string","enum":["rule","procedure"]},"polarity":{"type":"string","enum":["positive","negative"]},"title":text(256),"content":text(2048)})),"evidence":evidence,"unresolvedQuestions":array(text(512),12)}),
    );
    let assessment = if covering {
        object(
            json!({"status":{"type":"string","enum":["supported","rejected","unknown"]},
            // Positive and negative legacy results have distinct contracts; the adapter validates them.
            "result":if finalizing {json!({"type":"null"})}else{result_schema(negative)},"claims":array(object(json!({"claim":text(1024),"supported":{"type":"boolean"},"evidence":evidence})),64),"materialGaps":array(text(512),12)}),
        )
    } else {
        json!({"type":"null"})
    };
    let schema = object(json!({"version":{"type":"integer","enum":[1]},
        "candidates":array(candidate,if covering {0}else{20}),"assessment":assessment,
        "questions":array(object(json!({"id":text(128),"candidateKey":text(128),"question":text(512),"successCriteria":text(512),"resolved":{"type":"boolean"}})),12),
        "evidence":evidence,"next":{"anyOf":[
            object(json!({"kind":{"type":"string","enum":["read_source"]},"snapshot_hash":text(128),"from_byte":{"type":"integer","minimum":0},"to_byte":{"type":"integer","minimum":1},"question_id":text(128),"expected_gain":text(512)})),
            object(json!({"kind":{"type":"string","enum":["lookup_knowledge"]},"query":text(512),"question_id":text(128),"expected_gain":text(512)})),
            object(json!({"kind":{"type":"string","enum":["delegate_research"]},"question_ids":array(text(128),12),"expected_gain":text(512)})),
            object(json!({"kind":{"type":"string","enum":["finish"]},"reason":text(512)}))]}}));
    json!({"type":"json_schema","json_schema":{"name":if covering {"covering_agent"} else {"finding_agent"},"strict":true,"schema":schema}})
}

fn applicability() -> Value {
    // Project identity is injected by the host, never generated by the model.
    object(
        json!({"general":{"type":"boolean"},"technologies":array(text(128),16),"changeTypes":array(text(128),16),"domains":array(text(128),16)}),
    )
}
fn result_schema(negative: bool) -> Value {
    if negative {
        object(
            json!({"status":{"type":"string","enum":["ready","insufficient"]},"polarity":{"type":"string","enum":["negative"]},"intentTags":array(json!({"type":"string","enum":["guidance","guardrail","prohibition","warning","failure_pattern","review_finding","regression","test_gap","verification","preference","boundary_violation","architecture_risk","security_risk","performance_risk","operational_risk","data_integrity"]}),16),"appliesTo":applicability(),"distilled":object(json!({"failure":text(1024),"impact":{"type":["string","null"],"maxLength":1024},"trigger":{"type":["string","null"],"maxLength":1024},"fix":{"type":["string","null"],"maxLength":1024},"verification":{"type":["string","null"],"maxLength":1024},"decisionSignal":{"type":["string","null"],"maxLength":1024}})),"evidence":array(text(1024),16),"originRefs":array(text(512),16)}),
        )
    } else {
        object(
            json!({"status":{"type":"string","enum":["knowledge_ready","insufficient","duplicate"]},"stage":{"type":"string","enum":["final"]},"candidate":{"anyOf":[json!({"type":"null"}),object(json!({"type":{"type":"string","enum":["rule","procedure"]},"title":text(256),"body":text(2048),"importance":{"type":"integer","minimum":0,"maximum":100},"confidence":{"type":"integer","minimum":0,"maximum":100},"appliesTo":applicability()}))]}}),
        )
    }
}

pub(crate) fn result_example(negative: bool) -> Value {
    let applies = json!({"general":false,"technologies":["technology"],"changeTypes":["change type"],"domains":["domain"]});
    if negative {
        json!({"status":"ready","polarity":"negative","intentTags":["failure_pattern"],"appliesTo":applies,"distilled":{"failure":"observed failure","impact":null,"trigger":null,"fix":null,"verification":null,"decisionSignal":null},"evidence":["exact source quote"],"originRefs":[]})
    } else {
        json!({"status":"knowledge_ready","stage":"final","candidate":{"type":"rule","title":"title","body":"source supported body","importance":70,"confidence":70,"appliesTo":applies}})
    }
}
